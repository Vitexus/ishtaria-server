//! Towns that every world grows by itself, whatever datadisks it uses.
//!
//! A world has a few dozen settlements (`ISHTARIA_SETTLEMENTS`, default 36; 0 for none), each
//! with a graveyard outside its edge. They are ordinary places of a built-in disk named `world`,
//! so they are placed, persisted and described like any other place. After placement, settlements
//! by the sea get a harbour with a shipwright (a second built-in disk, `harbours`) who sells boats
//! and ships for gold.

use super::{
    disk::Structure,
    disk::{Dialogue, Disk, HeightRange, Manifest, Music, Near, Npc, Place, Requires, Scenery},
    placement::{self, Ground, Placed},
    Story,
};
use crate::movement::WorldObject;
use crate::scenery::{self, LocalProp, Size};
use anyhow::Result;
