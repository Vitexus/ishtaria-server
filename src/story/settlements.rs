/// Directory with the files the server itself ships (override with `ISHTARIA_ASSETS_DIR`).
const DEFAULT_ASSETS_DIR: &str = "/usr/share/ishtaria-server";
/// Default music of every generated graveyard, below the assets directory.
const GRAVEYARD_MUSIC: &str = "music/graveyard_midnightcem.ogg";
/// How far from a graveyard its music is heard.
const GRAVEYARD_MUSIC_RADIUS_M: f64 = 70.0;

fn assets_dir() -> PathBuf {
    std::env::var_os("ISHTARIA_ASSETS_DIR").map_or_else(
        || {
            if cfg!(test) {
                PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/assets"))
            } else {
                PathBuf::from(DEFAULT_ASSETS_DIR)
            }
        },
        PathBuf::from,
    )
}

/// How many settlements a world grows.
pub fn count() -> usize {
    // Tests build tiny worlds with no room for towns unless they ask for some.
    let default = if cfg!(test) { 0 } else { DEFAULT_COUNT };
    std::env::var("ISHTARIA_SETTLEMENTS")
        .ok()
        .and_then(|value| value.parse::<usize>().ok())
        .map_or(default, |value| value.min(200))
}

/// A model standing in the world, as sent to clients.
#[derive(Clone, Debug, Serialize, PartialEq)]
pub struct WorldProp {
    pub id: String,
    /// `<kit>.<name>` of a bundled Kenney kit model.
    pub model: String,
    pub position: [f64; 3],
    pub yaw: f64,
    /// Metres per model unit.
    pub scale_m: f64,
    /// Metres per model unit along the model's x, y and z when they differ (a building fitted to its plot); `scale_m`
    /// then holds the largest of them.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub scale_xyz: Option<[f64; 3]>,
    /// Set when the prop is a vehicle a player can board (its speed and the rider's clip).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub vehicle: Option<super::disk::Vehicle>,
    /// Distance up to which the prop is announced, when it is larger than the usual radius
    /// (the buildings of datadisks are seen from afar).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub visible_m: Option<f64>,
    /// A structure the player can read standing at it (`POST /story/places/{id}/read`; the id is the place's).
    #[serde(skip_serializing_if = "std::ops::Not::not")]
    pub readable: bool,
}

